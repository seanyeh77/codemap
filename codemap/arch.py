"""Layer 3, generated part: components, the calls between them and the
relations that cross a process or language boundary, written into CODEMAP.md
between markers so that hand- or AI-written text around them is kept."""

import html
import re
import shutil
import subprocess
from collections import Counter, defaultdict
from pathlib import Path

BEGIN, END = "<!-- codemap:architecture:begin -->", "<!-- codemap:architecture:end -->"
TOP_DIRS = {"src", "lib", "include", "pkg", "internal", "cmd", "apps"}
LIBC = re.compile(r"^/usr/include/(?:[^/]+\.h|bits/|sys/|x86_64-linux-gnu/|linux/|asm|c\+\+/)")


def component(path, config=None):
    for prefix, name in (config or {}).get("components", {}).items():
        if path == prefix or path.startswith(prefix.rstrip("/") + "/"):
            return name
    parts = path.split("/")
    if len(parts) > 2 and parts[0] in TOP_DIRS:
        return "/".join(parts[:2])
    return parts[0] if len(parts) > 1 else "(root)"


def external(decl_file):
    if not decl_file or not decl_file.startswith("/") or LIBC.match(decl_file):
        return None
    m = re.match(r"^/usr/(?:local/)?include/([^/]+)/", decl_file)
    return f"external {m.group(1)}" if m else None


def summarize(index, config=None):
    nodes, edges = index["nodes"], index["edges"]
    comp_of = lambda nid: component(nodes[nid]["file"], config) if nid in nodes and nodes[nid].get("file") and not nodes[nid]["file"].startswith("/") else None
    comps = defaultdict(lambda: dict(files=set(), funcs=set(), main=[], ctor=[], exported=[]))
    called = set()
    for e in edges:
        if e["source"] == "compiler":
            called.add(e["dst"])
    for nid, n in nodes.items():
        if n.get("kind") == "site" or not n.get("defined") or not n.get("file") or n["file"].startswith("/"):
            continue
        c = comps[component(n["file"], config)]
        c["files"].add(n["file"])
        c["funcs"].add(nid)
        if n["name"] == "main":
            c["main"].append(nid)
        elif ":" not in nid and nid not in called:
            c["exported"].append(nid)
    calls = defaultdict(list)
    ext = defaultdict(list)
    for e in edges:
        if e["source"] != "compiler" or e["kind"] != "call":
            continue
        a = comp_of(e["src"])
        if not a:
            continue
        b = comp_of(e["dst"])
        if b is None and e["dst"] in nodes:
            x = external(nodes[e["dst"]].get("file"))
            if x:
                ext[(a, x)].append(e)
        elif b and b != a:
            calls[(a, b)].append(e)
    rules = [e for e in edges if e["source"] == "rule"]
    for e in rules:
        if e["kind"] in ("constructor", "destructor"):
            comps[component(e["file"], config)]["ctor"].append((e["dst"], e["kind"]))
    return comps, calls, ext, rules


def name(nodes, nid):
    return nodes[nid]["name"] if nid in nodes else nid


def loc(e):
    return f'`{e["file"]}:{e["line"]}`'


def render(index, config=None, svg_name=None):
    nodes = index["nodes"]
    comps, calls, ext, rules = summarize(index, config)
    out = [BEGIN, "", "## Architecture", "",
           "This section is generated by `codemap arch` from the index; do not edit it by hand. "
           "Edges marked compiler come from GCC `-fcallgraph-info`, edges marked rule come from text rules "
           "and should be read as candidates.", ""]
    if svg_name:
        out += [f"![Architecture]({svg_name})", ""]
    st = index["stats"]
    out += [f'Index: {st["units"]} translation units ({st["failed"]} failed), {st["edges"]} compiler edges, '
            f'{st["indirect"]} indirect calls of which {st.get("indirect_unresolved", st["indirect"])} are unresolved.', ""]

    out += ["### Components", "", "| Component | Files | Functions | Entry points |", "| --- | --- | --- | --- |"]
    for cname in sorted(comps, key=lambda k: -len(comps[k]["funcs"])):
        c = comps[cname]
        entries = [f'`{name(nodes, x)}` (main)' for x in c["main"]]
        entries += [f'`{name(nodes, x)}` ({kind})' for x, kind in sorted(set(c["ctor"]))]
        ex = sorted(name(nodes, x) for x in c["exported"])
        if ex:
            shown = ", ".join(f"`{x}`" for x in ex[:6])
            entries.append(f"{len(ex)} global functions with no caller in the repo: {shown}" + (", ..." if len(ex) > 6 else ""))
        out.append(f'| {cname} | {len(c["files"])} | {len(c["funcs"])} | {"; ".join(entries) or "-"} |')
    out.append("")

    out += ["### Calls between components", "", "| From | To | Calls | Example |", "| --- | --- | --- | --- |"]
    for (a, b), es in sorted(calls.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        e = es[0]
        out.append(f'| {a} | {b} | {len(es)} | `{name(nodes, e["src"])} -> {name(nodes, e["dst"])}` at {loc(e)} |')
    out.append("")
    if ext:
        out += ["### Calls into external libraries", "", "| From | Library | Calls | Distinct functions |", "| --- | --- | --- | --- |"]
        for (a, x), es in sorted(ext.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            out.append(f'| {a} | {x.replace("external ", "")} | {len(es)} | {len({e["dst"] for e in es})} |')
        out.append("")

    out += ["### Relations the compiler does not see", ""]
    groups = defaultdict(list)
    for e in rules:
        groups[e["rule"]].append(e)

    def rows(title, es, fmt, limit=12):
        if not es:
            return
        out.extend([f"#### {title}", ""])
        for e in es[:limit]:
            out.append("- " + fmt(e))
        if len(es) > limit:
            out.append(f"- and {len(es) - limit} more")
        out.append("")

    rows("Started as a process", [e for e in groups["exec"] if e["file"].endswith((".c", ".h", ".cc", ".cpp"))],
         lambda e: f'`{name(nodes, e["src"])}` calls `{e["call"]}` at {loc(e)}')
    env = [e for e in groups["env"] if not e["file"].endswith(".py")]
    rows("Environment variables", env,
         lambda e: f'`{e["name"]}` is set by `{name(nodes, e["src"])}` at {loc(e)} and read by '
                   f'`{name(nodes, e["dst"])}` at `{e["read_at"]}`')
    rows("Run by the loader", groups["ctor"],
         lambda e: f'`{name(nodes, e["dst"])}` is a {e["kind"]}, declared at {loc(e)}')
    rows("Functions stored in pointers", groups["fnptr_assign"],
         lambda e: f'`{name(nodes, e["src"])}` stores `{name(nodes, e["dst"])}` in `{e["slot"]}` at {loc(e)}')
    rows("Indirect calls resolved by rules", groups["indirect"],
         lambda e: (f'`{name(nodes, e["src"])}` calls through `{e["via"]}` at {loc(e)}, which holds '
                    + (f'`{name(nodes, e["dst"])}`' if e["kind"] == "indirect_candidate"
                       else f'the previous value of `{e["saved_from"]}` saved at `{nodes[e["dst"]]["file"]}:{nodes[e["dst"]]["line"]}`')))
    rows("Set by the build", groups["build_define"],
         lambda e: f'`{e["name"]}` is set to `{e["value"]}` at {loc(e)}; used at `{nodes[e["dst"]]["file"]}:{nodes[e["dst"]]["line"]}`'
         if e.get("value") else f'`{e["name"]}` is defined at {loc(e)}; used at `{nodes[e["dst"]]["file"]}:{nodes[e["dst"]]["line"]}`')
    rows("Shared between C and Python", groups["cross_lang"],
         lambda e: f'{loc(e)} refers to `{e["name"]}`' + (f', next to `{e["near"].split(":")[0]}` at `{e["file"]}:{e["near"].split(":")[1]}`' if e.get("near") else ""))
    out += [END, ""]
    return "\n".join(out)


def write_codemap(root, text):
    p = Path(root) / "CODEMAP.md"
    old = p.read_text() if p.exists() else "# Codemap\n\n"
    if BEGIN in old and END in old:
        new = old[:old.index(BEGIN)] + text.rstrip() + "\n" + old[old.index(END) + len(END):].lstrip("\n")
    else:
        new = old.rstrip() + "\n\n" + text
    p.write_text(new)
    return p


